export const MEAL_DATABASE = {
  breakfasts: BREAKFASTS,
  lunches: LUNCHES,
  dinners: DINNERS,
  snacks: SNACKS,
};

export function getMealsByType(type: MealType): Meal[] {
  switch (type) {
    case 'breakfast':
      return BREAKFASTS;
    case 'lunch':
      return MEAL_DATABASE.lunches;
    case 'dinner':
      return MEAL_DATABASE.dinners;
    case 'snack':
      return SNACKS;
    default:
      return [];
  }
}

export function getMealById(id: string): Meal | undefined {
  return [...BREAKFASTS, ...LUNCHES, ...DINNERS, ...SNACKS].find(meal => meal.id === id);
}
